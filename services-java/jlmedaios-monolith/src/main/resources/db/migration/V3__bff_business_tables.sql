-- 1. 临床改进任务
CREATE TABLE IF NOT EXISTS improvement_tasks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_no     VARCHAR(50),
    title       VARCHAR(200),
    category    VARCHAR(50),
    priority    VARCHAR(20),
    status      VARCHAR(20) DEFAULT 'open',
    assignee    VARCHAR(100),
    due_date    DATE,
    tenant_id   VARCHAR(50),
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_improvement_task_no ON improvement_tasks(task_no);
CREATE INDEX IF NOT EXISTS idx_improvement_task_status ON improvement_tasks(status);
CREATE INDEX IF NOT EXISTS idx_improvement_task_assignee ON improvement_tasks(assignee);

-- 2. 在院费用监控
CREATE TABLE IF NOT EXISTS inpatient_cost_monitor (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id          VARCHAR(50),
    ward_code           VARCHAR(20),
    total_cost          DECIMAL(12,2),
    cost_warning_level  VARCHAR(20),
    tenant_id           VARCHAR(50),
    created_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_cost_monitor_patient ON inpatient_cost_monitor(patient_id);
CREATE INDEX IF NOT EXISTS idx_cost_monitor_ward ON inpatient_cost_monitor(ward_code);

-- 3. 病组选择
CREATE TABLE IF NOT EXISTS payment_selection (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id      VARCHAR(50),
    drg_group       VARCHAR(50),
    dip_group       VARCHAR(50),
    selected_mode   VARCHAR(20),
    status          VARCHAR(20),
    tenant_id       VARCHAR(50),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_payment_selection_patient ON payment_selection(patient_id);
CREATE INDEX IF NOT EXISTS idx_payment_selection_mode ON payment_selection(selected_mode);

-- 4. 续方流转
CREATE TABLE IF NOT EXISTS renewal_flow (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id      VARCHAR(50),
    drug_name       VARCHAR(200),
    status          VARCHAR(20) DEFAULT 'pending_review',
    doctor_name     VARCHAR(100),
    tenant_id       VARCHAR(50),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_renewal_patient ON renewal_flow(patient_id);
CREATE INDEX IF NOT EXISTS idx_renewal_status ON renewal_flow(status);

-- 5. 排班槽位
CREATE TABLE IF NOT EXISTS schedule_slots (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_code   VARCHAR(20),
    doctor_id   VARCHAR(50),
    slot_date   DATE,
    time_slot   VARCHAR(20),
    status      VARCHAR(20) DEFAULT 'open',
    tenant_id   VARCHAR(50),
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_schedule_dept ON schedule_slots(dept_code);
CREATE INDEX IF NOT EXISTS idx_schedule_date ON schedule_slots(slot_date);
CREATE INDEX IF NOT EXISTS idx_schedule_doctor ON schedule_slots(doctor_id);

-- 6. 结算分析
CREATE TABLE IF NOT EXISTS settlement_analytics (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_month    VARCHAR(7),
    total_amount    DECIMAL(14,2),
    patient_count   INT,
    avg_cost        DECIMAL(12,2),
    tenant_id       VARCHAR(50),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_settlement_period ON settlement_analytics(period_month);

-- 7. 结算钻取
CREATE TABLE IF NOT EXISTS settlement_drilldown (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_code       VARCHAR(20),
    doctor_id       VARCHAR(50),
    patient_count   INT,
    total_amount    DECIMAL(14,2),
    period_month    VARCHAR(7),
    tenant_id       VARCHAR(50),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_drilldown_dept ON settlement_drilldown(dept_code);
CREATE INDEX IF NOT EXISTS idx_drilldown_period ON settlement_drilldown(period_month);

-- 8. 结算报表
CREATE TABLE IF NOT EXISTS settlement_report (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_month    VARCHAR(7),
    report_type     VARCHAR(50),
    total_amount    DECIMAL(14,2),
    patient_count   INT,
    tenant_id       VARCHAR(50),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_report_month ON settlement_report(report_month);

-- 9. 手术排程
CREATE TABLE IF NOT EXISTS surgery_schedule (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    surgery_no          VARCHAR(50),
    patient_id          VARCHAR(50),
    surgeon             VARCHAR(100),
    or_room             VARCHAR(50),
    scheduled_start     TIMESTAMP,
    status              VARCHAR(20) DEFAULT 'scheduled',
    tenant_id           VARCHAR(50),
    created_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_surgery_no ON surgery_schedule(surgery_no);
CREATE INDEX IF NOT EXISTS idx_surgery_patient ON surgery_schedule(patient_id);
CREATE INDEX IF NOT EXISTS idx_surgery_room ON surgery_schedule(or_room);

-- 10. 管路护理
CREATE TABLE IF NOT EXISTS tube_care (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id      VARCHAR(50),
    tube_type       VARCHAR(50),
    insert_date     DATE,
    care_status     VARCHAR(20) DEFAULT 'in_place',
    nurse_in_charge VARCHAR(100),
    tenant_id       VARCHAR(50),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_tube_patient ON tube_care(patient_id);
CREATE INDEX IF NOT EXISTS idx_tube_status ON tube_care(care_status);

-- 11. 驾驶舱统计
CREATE TABLE IF NOT EXISTS dashboard_stats (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stat_key    VARCHAR(100),
    stat_value  DECIMAL(14,2),
    period_date  DATE,
    tenant_id   VARCHAR(50),
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_stat_key ON dashboard_stats(stat_key);
CREATE INDEX IF NOT EXISTS idx_stat_date ON dashboard_stats(period_date);

-- 12. 急诊队列
CREATE TABLE IF NOT EXISTS emergency_queue (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_no        VARCHAR(50),
    patient_id      VARCHAR(50),
    triage_level    VARCHAR(10),
    arrival_time    TIMESTAMP,
    status          VARCHAR(20) DEFAULT 'waiting',
    tenant_id       VARCHAR(50),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_emergency_visit ON emergency_queue(visit_no);
CREATE INDEX IF NOT EXISTS idx_emergency_triage ON emergency_queue(triage_level);
CREATE INDEX IF NOT EXISTS idx_emergency_status ON emergency_queue(status);

-- 13. 药房发药
CREATE TABLE IF NOT EXISTS pharmacy_dispense (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispense_no     VARCHAR(50),
    patient_id      VARCHAR(50),
    drug_name       VARCHAR(200),
    quantity        INT,
    status          VARCHAR(20) DEFAULT 'dispensed',
    tenant_id       VARCHAR(50),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_dispense_no ON pharmacy_dispense(dispense_no);
CREATE INDEX IF NOT EXISTS idx_dispense_patient ON pharmacy_dispense(patient_id);

-- 14. 病案首页
CREATE TABLE IF NOT EXISTS front_page_records (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_no               VARCHAR(50),
    patient_id              VARCHAR(50),
    admission_diagnosis     TEXT,
    discharge_diagnosis     TEXT,
    status                  VARCHAR(20) DEFAULT 'draft',
    tenant_id               VARCHAR(50),
    created_at              TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_frontpage_no ON front_page_records(record_no);
CREATE INDEX IF NOT EXISTS idx_frontpage_patient ON front_page_records(patient_id);
CREATE INDEX IF NOT EXISTS idx_frontpage_status ON front_page_records(status);
