/** 入院天数计算基准：2026-09-16 */
const NOW = '2026-09-16';
function calcStayDays(admitDate: string): number {
  const diff = new Date(NOW).getTime() - new Date(admitDate.slice(0, 10)).getTime();
  return Math.max(0, Math.round(diff / 86400000));
}

