const focusPool: Record<string, string[]> = {
  critical: ['凌晨心肌酶学复查肌钙蛋白升高', '需警惕心律失常发作', '关注出入量及血压波动'],
  serious: ['昨日夜间血氧下降至89%', '利尿剂效果待评估', '今日复查BNP及电解质'],
  normal: ['待回报冠脉CTA结果', '晨起血压158/96偏高', '无特殊异常'],
};

function buildRoundList(): RoundPatient[] {
  return mockPatients.map((p, idx) => {
    const bedNo =
      mockRoomGroups.flatMap((g) => g.beds).find((bed) => bed.patient?.id === p.id)?.bedNo ?? '-';
    const isNewAdmit = p.stayDays <= 2;
    const isTodaySurgery = !!p.todaySurgery;
    const isPendingDischarge =
      p.pathway === 'on_path' && p.stayDays >= 6 && p.condition === 'normal';
    const isKeyPatient = p.condition !== 'normal' || isTodaySurgery || isNewAdmit;
    const focusPoolFor = focusPool[p.condition] ?? focusPool.normal;
    const roundStatus: RoundPatient['roundStatus'] =
      idx % 11 === 3 || idx % 11 === 7 ? 'finished' : idx % 11 === 5 ? 'in_progress' : 'pending';
    return {
      patient: p,
      bedNo,
      focusPoints: focusPoolFor.slice(0, 2 + (idx % 2)),
      roundStatus,
      thirdRound: {
        resident: roundStatus === 'pending' ? idx % 3 !== 0 : true,
        attending: roundStatus === 'pending' ? idx % 4 !== 0 : true,
        chief: roundStatus === 'finished',
      },
      isNewAdmit,
      isTodaySurgery,
      isPendingDischarge,
      isKeyPatient,
    };
  });
}

export const mockRoundList: RoundPatient[] = buildRoundList();

