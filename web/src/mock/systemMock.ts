function buildDictItems(prefix: string, names: string[]): DictItem[] {
  return names.map((n, i) => ({
    id: `${prefix}_${i + 1}`,
    dictCode: `${prefix}${String(i + 1).padStart(3, '0')}`,
    dictName: n,
    dictValue: String(i + 1),
    sort: i + 1,
    status: i % 7 === 6 ? 'disabled' : 'enabled',
    remark: i % 3 === 0 ? `${n}相关说明` : undefined,
  }));
}

