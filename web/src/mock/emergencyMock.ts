function gcNode(
  key: string,
  label: string,
  targetMin: number,
  elapsedMin?: number,
): GCTimelineNode {
  const done = elapsedMin != null;
  return {
    key,
    label,
    targetMinutes: targetMin,
    time: elapsedMin != null ? inAgo(elapsedMin) : undefined,
    done,
    overdue: done && elapsedMin! > targetMin,
  };
}

