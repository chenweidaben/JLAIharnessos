/** 根据主诉与生命体征生成 AI 辅助分诊建议 */
export function buildAiAdvice(chiefComplaint: string, vitals: Vitals): AITriageAdvice {
  let matched = KEYWORD_RULES[KEYWORD_RULES.length - 1];
  for (const rule of KEYWORD_RULES) {
    if (rule.keys.some((k) => chiefComplaint.includes(k))) {
      matched = rule;
      break;
    }
  }
  // 生命体征恶化自动升级
  let level: TriageLevel = matched.level;
  const reasons: string[] = [];
  if (vitals.spo2 != null && vitals.spo2 < 90) {
    level = 1;
    reasons.push('SpO₂<90%，提示严重低氧');
  } else if (vitals.systolic != null && vitals.systolic < 90) {
    level = 1;
    reasons.push('收缩压<90mmHg，提示休克');
  } else if (vitals.consciousness === 'unresponsive' || vitals.consciousness === 'pain') {
    level = 1;
    reasons.push('意识障碍（仅对疼痛/无反应）');
  } else if (vitals.consciousness === 'verbal') {
    level = Math.min(level, 2) as TriageLevel;
    reasons.push('意识模糊（对声音反应）');
  } else if (vitals.spo2 != null && vitals.spo2 < 94) {
    level = Math.min(level, 2) as TriageLevel;
    reasons.push('SpO₂<94%');
  }
  if (vitals.temperature != null && vitals.temperature >= 39) {
    reasons.push(`高热 ${vitals.temperature}℃`);
  }
  return {
    suggestedLevel: level,
    immediateActions: reasons.length
      ? [...reasons, ...matched.immediate.slice(0, 2)]
      : matched.immediate,
    differentialDx: matched.differential,
    suggestedExams: matched.exams,
  };
}

